// Writes src/game/asset-versions.ts: a short content hash per media folder.
// Media is served with a one-year immutable cache, so every URL carries ?v=<hash>;
// re-recording a voice line or re-cutting a picture changes the hash and phones fetch the new file.
// Runs before every build — run it by hand after changing files in public/ during development.
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIRS = ["art", "sfx", "voice", "music"];
const out = {};
for (const dir of DIRS) {
  const root = join("public", dir);
  const hash = createHash("sha1");
  if (existsSync(root)) {
    for (const name of readdirSync(root).sort()) {
      hash.update(name);
      hash.update(readFileSync(join(root, name)));
    }
  }
  out[dir] = hash.digest("hex").slice(0, 8);
}
const body = `// Generated by tools/asset-versions.mjs — do not edit by hand.
export const ASSET_VERSIONS: Record<string, string> = ${JSON.stringify(out, null, 2)};
`;
const target = "src/game/asset-versions.ts";
const before = existsSync(target) ? readFileSync(target, "utf8") : "";
if (before !== body) writeFileSync(target, body);
console.log("asset versions", out);
